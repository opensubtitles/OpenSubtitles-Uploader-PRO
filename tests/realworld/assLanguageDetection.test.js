/**
 * Regression fixture: real excerpts from the three ASS subtitle tracks of
 * "Digimon Beatbreak S01E01 1080p CR WEB-DL AAC2.0 H.264-OldT.mkv", the
 * Crunchyroll release that exposed the detection bug.
 *
 * The MKV tagged its tracks correctly (eng / spa / por, named "English",
 * "Latin American Spanish", "Brazilian Portuguese") and the dialogue really is
 * in those three languages. But the v1.9.0 pure-JS MKV fast path emits raw
 * .ass, and the detection endpoint samples a file's first ~100 lines - which
 * for ASS is the [Script Info] + [V4+ Styles] header. The server answered
 * `content_preview: "ScriptType: v4.00+ Collisions: Normal PlayResX: 640 ..."`
 * with `en=0.192, de=0.070, ru=0.063` for all three tracks, so every track
 * showed up as English.
 *
 * The headers below are not byte-identical (font sizes and margins differ) but
 * every token in them is language-neutral ASCII, which is why the three
 * responses matched to 17 decimal places.
 *
 * Live verification of the fix against the real API, these same payloads:
 *   track 0 -> en 94.2%   track 1 -> es 99.6%   track 2 -> pt 99.7%
 */
