const KEYS = Object.keys(TRACKS);
const buildTrack = key => `${TRACKS[key].header}\n${TRACKS[key].dialogue.join('\n')}\n`;

describe('Digimon Beatbreak S01E01 - three ASS tracks all reported as English', () => {
  test('each track reduces to its own dialogue, not the ASS header', () => {
    for (const key of KEYS) {
      const { text, format, lines } = extractDialogueText(buildTrack(key), { maxChars: 5120 });

      assert.equal(format, 'ass', `${key}: format`);
      assert.equal(lines, 6, `${key}: expected 6 dialogue lines, got ${lines}`);
      assert.ok(!text.includes('ScriptType'), `${key}: header leaked`);
      assert.ok(!text.includes('Trebuchet'), `${key}: style block leaked`);
      assert.ok(!text.includes('BottomCenter'), `${key}: style name leaked`);
      assert.ok(!text.includes('Dialogue:'), `${key}: event prefix leaked`);
      assert.ok(!/\d:\d\d:\d\d\.\d\d/.test(text), `${key}: timecode leaked`);
      assert.ok(!text.includes('{'), `${key}: override block leaked`);
    }
  });

  test('the three payloads are distinct - this is the bug', () => {
    const payloads = KEYS.map(key => extractDialogueText(buildTrack(key)).text);
    assert.equal(new Set(payloads).size, 3, 'two tracks produced an identical detection payload');
  });

  test('language-distinguishing words survive stripping', () => {
    for (const key of KEYS) {
      const { text } = extractDialogueText(buildTrack(key));
      assert.ok(text.includes(TRACKS[key].opener), `${key}: ${TRACKS[key].label} opener missing`);
    }
  });

  test('the header alone yields nothing, so detection never runs on it', () => {
    for (const key of KEYS) {
      assert.equal(extractDialogueText(TRACKS[key].header).text, '', `${key}: header produced text`);
    }
  });

  test('stripping removes the ASCII bulk that drowned out the language', () => {
    for (const key of KEYS) {
      const raw = buildTrack(key);
      const { text } = extractDialogueText(raw);
      // Header plus per-event scaffolding was the majority of every sample.
      assert.ok(
        text.length < raw.length * 0.35,
        `${key}: expected a large reduction, ${raw.length} -> ${text.length}`
      );
    }
  });
});
