import { test, describe } from 'node:test';
import assert from 'node:assert';
import { extractDialogueText } from '../../src/utils/subtitleDetectionText.js';

/**
 * Header lifted from the Crunchyroll "Digimon Beatbreak S01E01" MKV that
 * exposed the bug: identical across its English, Latin-American Spanish and
 * Brazilian Portuguese ASS tracks, which is why the detection endpoint answered
 * English for all three.
 */
const ASS_HEADER = `[Script Info]
ScriptType: v4.00+
Collisions: Normal
PlayResX: 640
PlayResY: 360
Timer: 0.0000
WrapStyle: 0
ScaledBorderAndShadow: yes

[V4+ Styles]
Format: Name, Fontname, Fontsize, PrimaryColour, SecondaryColour, OutlineColour, BackColour, Bold, Italic, Underline, StrikeOut, ScaleX, ScaleY, Spacing, Angle, BorderStyle, Outline, Shadow, Alignment, MarginL, MarginR, MarginV, Encoding
Style: BottomCenter,Trebuchet MS,21,&H00FFFFFF,&H00FFFFFF,&H00000000,&H00000000,-1,0,0,0,100,100,0,0,1,1.5,0,2,0020,0020,0022,1
Style: TopCenter,Trebuchet MS,21,&H00FFFFFF,&H00FFFFFF,&H00000000,&H00000000,-1,0,0,0,100,100,0,0,1,1.5,0,8,0020,0020,0022,1

[Events]
Format: Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text
`;

const assFile = events => `${ASS_HEADER}${events}`;

describe('extractDialogueText - ASS', () => {
  test('drops the header and every event field, keeping only spoken text', () => {
    const content = assFile(
      `Dialogue: 0,0:00:16.10,0:00:20.15,BottomCenter,,0,0,0,,{\\i1}En el futuro cercano, el e-Pulse,{\\i0}\\N{\\i1}creado de los pensamientos y emociones,{\\i0}
Dialogue: 0,0:02:05.75,0:02:06.75,BottomCenter,,0,0,0,,Ahí está.
`
    );

    const { text, format, lines } = extractDialogueText(content);

    assert.equal(format, 'ass');
    assert.equal(lines, 2);
    assert.equal(
      text,
      'En el futuro cercano, el e-Pulse, creado de los pensamientos y emociones,\nAhí está.'
    );
    // The things that used to dominate the sample are all gone.
    assert.ok(!text.includes('ScriptType'));
    assert.ok(!text.includes('BottomCenter'));
    assert.ok(!text.includes('Trebuchet'));
    assert.ok(!text.includes('0:00:16.10'));
    assert.ok(!text.includes('\\i1'));
  });

  test('two tracks differing only in language no longer share a payload', () => {
    const spanish = extractDialogueText(
      assFile('Dialogue: 0,0:00:01.00,0:00:02.00,BottomCenter,,0,0,0,,Ahí está.\n')
    ).text;
    const portuguese = extractDialogueText(
      assFile('Dialogue: 0,0:00:01.00,0:00:02.00,BottomCenter,,0,0,0,,Lá está ele.\n')
    ).text;

    assert.notEqual(spanish, portuguese);
    assert.equal(spanish, 'Ahí está.');
    assert.equal(portuguese, 'Lá está ele.');
  });

  test('excludes Comment events, which carry translator notes in other languages', () => {
    const content = assFile(
      `Comment: 0,0:00:01.00,0:00:02.00,BottomCenter,,0,0,0,,TRANSLATOR NOTE: check this sign later
Dialogue: 0,0:00:03.00,0:00:04.00,BottomCenter,,0,0,0,,Lá está ele.
`
    );

    assert.equal(extractDialogueText(content).text, 'Lá está ele.');
  });

  test('skips vector drawing events whose payload is coordinates', () => {
    const content = assFile(
      `Dialogue: 0,0:00:01.00,0:00:02.00,BottomCenter,,0,0,0,,{\\p1}m 0 0 l 100 0 100 100 0 100{\\p0}
Dialogue: 0,0:00:03.00,0:00:04.00,BottomCenter,,0,0,0,,Real words here.
`
    );

    const { text, lines } = extractDialogueText(content);
    assert.equal(lines, 1);
    assert.equal(text, 'Real words here.');
  });

  test('skips events whose text is nothing but override blocks', () => {
    const content = assFile(
      `Dialogue: 0,0:00:01.00,0:00:02.00,BottomCenter,,0,0,0,,{\\pos(320,100)}
Dialogue: 0,0:00:03.00,0:00:04.00,BottomCenter,,0,0,0,,Real words here.
`
    );

    assert.equal(extractDialogueText(content).lines, 1);
  });

  test('a header-only script yields no text, so the caller can fall back', () => {
    assert.equal(extractDialogueText(ASS_HEADER).text, '');
  });
});

describe('extractDialogueText - SRT and VTT', () => {
  test('drops indexes, timecodes and markup from SRT', () => {
    const content = `1
00:00:16,100 --> 00:00:20,150
<i>In the near future, e-Pulse is</i>
generated by human thoughts.

2
00:00:20,440 --> 00:00:24,070
{\\an8}And used as an energy source.
`;

    const { text, format } = extractDialogueText(content);
    assert.equal(format, 'srt');
    assert.equal(
      text,
      'In the near future, e-Pulse is\ngenerated by human thoughts.\nAnd used as an energy source.'
    );
  });

  test('drops the WEBVTT header and NOTE blocks', () => {
    const content = `WEBVTT

NOTE this is a production note

1
00:00:16.100 --> 00:00:20.150
Num futuro próximo.
`;

    const { text, format } = extractDialogueText(content);
    assert.equal(format, 'vtt');
    assert.equal(text, 'Num futuro próximo.');
  });

  test('strips a leading BOM rather than prepending it to the first cue', () => {
    const content = `${'\uFEFF'}1
00:00:01,000 --> 00:00:02,000
Hello there.
`;
    assert.equal(extractDialogueText(content).text, 'Hello there.');
  });
});

describe('extractDialogueText - MicroDVD', () => {
  test('drops frame markers and converts pipe breaks', () => {
    const content = `{100}{200}/Hello there.|Second line.
{300}{400}More words.
`;
    const { text, format } = extractDialogueText(content);
    assert.equal(format, 'microdvd');
    assert.equal(text, 'Hello there. Second line.\nMore words.');
  });
});

describe('extractDialogueText - bounds', () => {
  test('truncates on a line boundary without splitting a cue', () => {
    const content = assFile(
      `Dialogue: 0,0:00:01.00,0:00:02.00,BottomCenter,,0,0,0,,AAAAA
Dialogue: 0,0:00:03.00,0:00:04.00,BottomCenter,,0,0,0,,BBBBB
Dialogue: 0,0:00:05.00,0:00:06.00,BottomCenter,,0,0,0,,CCCCC
`
    );

    // 'AAAAA' + '\n' + 'BBBBB' = 11 chars; adding CCCCC would need 17.
    const { text, lines } = extractDialogueText(content, { maxChars: 11 });
    assert.equal(lines, 2);
    assert.equal(text, 'AAAAA\nBBBBB');
    assert.ok(text.length <= 11);
  });

  test('never exceeds maxChars', () => {
    const content = assFile(
      Array.from(
        { length: 400 },
        (_, i) =>
          `Dialogue: 0,0:00:01.00,0:00:02.00,BottomCenter,,0,0,0,,Line number ${i} of dialogue.`
      ).join('\n')
    );

    const { text } = extractDialogueText(content, { maxChars: 5120 });
    assert.ok(text.length <= 5120);
    assert.ok(text.length > 4000, `expected a full sample, got ${text.length}`);
  });

  test('unknown formats are passed through, capped', () => {
    const { text, format } = extractDialogueText('just some prose with no subtitle structure', {
      maxChars: 9,
    });
    assert.equal(format, 'unknown');
    assert.equal(text, 'just some');
  });
});
