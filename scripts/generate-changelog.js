#!/usr/bin/env node

/**
 * Generate changelog from GitHub releases
 * This script fetches releases from GitHub API and creates embedded changelog files
 */

import https from 'https';
import fs from 'fs';
import path from 'path';
import { execFileSync } from 'child_process';
import { fileURLToPath } from 'url';
import { withCurrentRelease } from './lib/changelogEntries.js';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const repoRoot = path.join(__dirname, '..');

console.log('📝 Generating embedded changelog from GitHub releases...');

const currentVersion = JSON.parse(
  fs.readFileSync(path.join(repoRoot, 'package.json'), 'utf8')
).version;

/**
 * Resolves the `🚀 RELEASE: Version X.Y.Z` commit for a version.
 *
 * Returns null when it cannot be found - no git, not a repo, or a shallow
 * clone whose history was cut off before the release commit.
 */
const lookupReleaseCommit = version => {
  let raw;
  try {
    raw = execFileSync(
      'git',
      [
        'log',
        '--max-count=1',
        '--format=%aI%x1f%B',
        '--fixed-strings',
        `--grep=🚀 RELEASE: Version ${version}`,
      ],
      { cwd: repoRoot, encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'] }
    ).trim();
  } catch {
    return null;
  }

  if (!raw) return null;
  const separator = raw.indexOf('\u001f');
  if (separator === -1) return null;

  return {
    authoredAt: raw.slice(0, separator),
    message: raw.slice(separator + 1),
  };
};

// Ensure data directory exists
const dataDir = path.join(__dirname, '..', 'src', 'data');
if (!fs.existsSync(dataDir)) {
  fs.mkdirSync(dataDir, { recursive: true });
}

const options = {
  hostname: 'api.github.com',
  path: '/repos/opensubtitles/opensubtitles-uploader-pro/releases',
  headers: {
    'User-Agent': 'OpenSubtitles-Uploader-PRO',
    'Accept': 'application/vnd.github.v3+json'
  }
};

https.get(options, (res) => {
  let data = '';
  res.on('data', (chunk) => data += chunk);
  res.on('end', () => {
    try {
      const releases = JSON.parse(data);
      
      // Handle cases where API returns error or non-array (rate limit, outage)
      if (!Array.isArray(releases)) {
        console.log('⚠️ GitHub API returned non-array response:', releases);
        // Still emit the release being built - its notes come from the local
        // commit, so an API failure should not ship a completely blank
        // "What's new" panel.
        const localOnly = withCurrentRelease({ releases: [], version: currentVersion, lookupReleaseCommit }).map(release => ({
          version: release.tag_name,
          name: release.name,
          published_at: release.published_at,
          body: release.body || 'No release notes available.',
          html_url: release.html_url,
          prerelease: release.prerelease,
          assets: [],
        }));
        console.log(`🔄 Creating minimal changelog with ${localOnly.length} release(s)`);
        const emptyChangelog = {
          generated_at: new Date().toISOString(),
          generator: 'OpenSubtitles Uploader PRO Build System',
          total_releases: localOnly.length,
          releases: localOnly
        };

        // Write empty JSON changelog
        const changelogPath = path.join(dataDir, 'changelog.json');
        fs.writeFileSync(changelogPath, JSON.stringify(emptyChangelog, null, 2));
        console.log(`✅ Generated ${changelogPath} with ${localOnly.length} releases`);
        return;
      }
      
      // Filter out drafts and take latest 15 releases
      const validReleases = withCurrentRelease({
        releases: releases.filter(release => !release.draft),
        version: currentVersion,
        lookupReleaseCommit,
      }).slice(
        0,
        15
      );
      
      const changelog = {
        generated_at: new Date().toISOString(),
        generator: 'OpenSubtitles Uploader PRO Build System',
        total_releases: validReleases.length,
        releases: validReleases.map(release => ({
          version: release.tag_name,
          name: release.name,
          published_at: release.published_at,
          body: release.body || 'No release notes available.',
          html_url: release.html_url,
          prerelease: release.prerelease,
          assets: release.assets.map(asset => ({
            name: asset.name,
            download_url: asset.browser_download_url,
            size: asset.size
          }))
        }))
      };
      
      // Write JSON changelog
      const changelogPath = path.join(dataDir, 'changelog.json');
      fs.writeFileSync(changelogPath, JSON.stringify(changelog, null, 2));
      console.log(`✅ Generated ${changelogPath} with ${changelog.releases.length} releases`);
      
      // Generate markdown changelog
      let markdownContent = '# Changelog\n\n';
      markdownContent += '> This file is automatically generated from GitHub releases during build process\n\n';
      markdownContent += `*Last updated: ${new Date().toLocaleString()}*\n\n`;
      
      changelog.releases.forEach(release => {
        const versionName = release.name ? release.name.replace(release.version + ' - ', '') : '';
        markdownContent += `## ${release.version}${versionName ? ' - ' + versionName : ''}\n\n`;
        markdownContent += `*Released: ${new Date(release.published_at).toLocaleDateString()}*\n\n`;
        
        if (release.prerelease) {
          markdownContent += '**🚧 Pre-release**\n\n';
        }
        
        if (release.body && release.body.trim()) {
          markdownContent += release.body + '\n\n';
        }
        
        if (release.assets && release.assets.length > 0) {
          markdownContent += '**Downloads:**\n';
          release.assets.forEach(asset => {
            const sizeKB = Math.round(asset.size / 1024);
            markdownContent += `- [${asset.name}](${asset.download_url}) (${sizeKB} KB)\n`;
          });
          markdownContent += '\n';
        }
        
        markdownContent += '---\n\n';
      });
      
      const changelogMdPath = path.join(__dirname, '..', 'CHANGELOG.md');
      fs.writeFileSync(changelogMdPath, markdownContent);
      console.log(`✅ Generated ${changelogMdPath}`);
      
      console.log('🎉 Changelog generation completed successfully');
      
    } catch (error) {
      console.error('❌ Failed to parse GitHub API response:', error);
      process.exit(1);
    }
  });
}).on('error', (error) => {
  console.error('❌ Failed to fetch releases from GitHub:', error);
  console.error('   Make sure you have internet connection and GitHub is accessible');
  process.exit(1);
});